// Лабораторная работа, вариант 8 «Кафе». Задание 1.
// Стоимость заказа и скидка: по сумме заказа или по статусу студента.
//
// Входные данные:
//   cost      - стоимость заказа, неотрицательное число;
//   isStudent - признак студента: 1 - студент, 0 - нет.
//
// Правила:
//   cost >= 60  - скидка 10 %;
//   cost >= 30  - скидка 5 %;
//   студент     - скидка 7 %.
// Скидки не складываются: применяется одна, максимальная.
//
// Результат: выбранный процент скидки и итоговая сумма заказа.
// =============================================================================

#include <iostream>
using namespace std;

int main() {
    double cost;
    int isStudent;

    cout << "Введите стоимость заказа: ";
    cin >> cost;

    cout << "Студент (1 - да, 0 - нет): ";
    cin >> isStudent;

    if (cost < 0) {
        cout << "Ошибка: стоимость заказа не может быть отрицательной." << endl;
        return 1;
    }

    if (isStudent != 0 && isStudent != 1) {
        cout << "Ошибка: признак студента должен быть 0 или 1." << endl;
        return 1;
    }

    // Скидка по стоимости заказа
    double discount = 0.0;

    if (cost >= 60) {
        discount = 10.0;
    }
    else if (cost >= 30) {
        discount = 5.0;
    }

    // Студенческая скидка, если она больше
    if (isStudent == 1 && 7.0 > discount) {
        discount = 7.0;
    }

    double total = cost - cost * discount / 100.0;

    cout << "Стоимость заказа: " << cost << endl;
    cout << "Выбранная скидка: " << discount << " %" << endl;
    cout << "Итоговая сумма: " << total << endl;

    return 0;
}